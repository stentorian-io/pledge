import type { Loaded } from "./inventory";
import { statuses } from "./inventory";

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s+/g, " ");
const link = (path: string) => `../${path}`;

export function render(loaded: Loaded) {
  const { sources, references, inventory } = loaded;
  const lines = ["<!-- Generated by bun scripts/conformance/check.ts --write. -->", "",
    "Every indexed reference has an explicit disposition. Counts are inventory units,",
    "not equally weighted language features or a percentage of language correctness.", "",
    "| Pinned source | Indexed units | Verified | Partial | Unsupported | Unverified | Excluded |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"];
  for (const source of sources) {
    const counts = Object.fromEntries(statuses.map(status => [status, 0]));
    for (const assessment of inventory.assessments) counts[assessment.status] += assessment.references.filter(id => id.startsWith(`${source.id}:`)).length;
    const url = `https://github.com/${source.repository}/tree/${source.revision}`;
    lines.push(`| [${cell(source.name)}](${url}) | ${references.filter(r => r.id.startsWith(`${source.id}:`)).length} | ${statuses.map(status => counts[status]).join(" | ")} |`);
  }
  lines.push("", "### Assessed contracts", "",
    "A partial row establishes only the behavior described below. It does not certify",
    "the entire upstream clause, feature flag, syntax kind, option, or test case.", "",
    "| Contract | Layer | Status | References | Evidence | Limits |",
    "| --- | --- | --- | ---: | --- | --- |");
  for (const assessment of inventory.assessments.filter(a => a.status !== "unverified" && a.status !== "excluded")) {
    const tests = assessment.evidence.map(id => {
      const evidence = inventory.evidence.find(e => e.id === id)!;
      return `[${id}](${link(evidence.source)})`;
    }).join(", ");
    lines.push(`| ${cell(assessment.title)} | ${assessment.layer} | ${assessment.status} | ${assessment.references.length} | ${tests} | ${cell(assessment.reason)} |`);
  }
  lines.push("", "### Unverified and excluded coverage", "",
    "Unverified is an open coverage gap, including cases whose existing tests have",
    "not yet been traced to this baseline. Excluded is an explicit scope decision;",
    "neither is a passing conformance result.", "",
    "| Area | Status | References | Reason |", "| --- | --- | ---: | --- |");
  for (const assessment of inventory.assessments.filter(a => a.status === "unverified" || a.status === "excluded")) {
    lines.push(`| ${cell(assessment.title)} | ${assessment.status} | ${assessment.references.length} | ${cell(assessment.reason)} |`);
  }
  lines.push("", "### Declared execution profiles", "",
    "These are the exact environments selected by the coverage runner. A profile",
    "does not imply support for every language feature or every option combination.", "",
    "| Profile | Node versions | TypeScript versions | npm versions | Options | Limits |",
    "| --- | --- | --- | --- | --- | --- |");
  for (const profile of inventory.profiles) {
    lines.push(`| ${profile.id} | ${profile.node.join(", ")} | ${profile.typescript.join(", ") || "none required"} | ${profile.npm?.join(", ") || "none required"} | ${cell(JSON.stringify(profile.options))} | ${cell(profile.limitations)} |`);
  }
  lines.push("", "The [machine-readable inventory](coverage/inventory.json) includes exact test names,",
    "fixture cases, upstream provenance, and the complete reference assignments.",
    "[Source locks](coverage/sources.json) record immutable revisions and checksums.", "");
  return lines.join("\n");
}

export function updateDocument(source: string, generated: string) {
  const start = "<!-- language-coverage:start -->";
  const end = "<!-- language-coverage:end -->";
  if (source.split(start).length !== 2 || source.split(end).length !== 2 || source.indexOf(start) >= source.indexOf(end)) throw new Error("coverage document needs exactly one ordered generated region");
  return source.slice(0, source.indexOf(start) + start.length) + "\n\n" + generated + "\n" + source.slice(source.indexOf(end));
}
