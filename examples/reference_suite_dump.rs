//! Phase 25 helper — dumps the baseline expected-findings.json for ONE
//! reference-suite package by running the same pipeline as the test harness.
//!
//! Invoked by scripts/regen-reference-suite.sh; not used in CI directly.
//!
//! Usage: reference_suite_dump <pkg>
//!   where <pkg> is one of: react, zod, prisma, tanstack-query, trpc

use std::collections::HashSet;
use std::path::{Path, PathBuf};

use interlint::acquire::extract_tgz_from_bytes;
use interlint::compare;
use interlint::discover::discover_exports;
use interlint::types::Finding;

fn main() {
    let pkg = std::env::args()
        .nth(1)
        .expect("usage: reference_suite_dump <pkg>");

    let dir: PathBuf = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/reference-suite")
        .join(&pkg);

    let from_bytes = std::fs::read(dir.join("from.tgz")).expect("read from.tgz");
    let to_bytes = std::fs::read(dir.join("to.tgz")).expect("read to.tgz");

    let (_old_dir, old_root) = extract_tgz_from_bytes(&from_bytes).expect("extract from");
    let (_new_dir, new_root) = extract_tgz_from_bytes(&to_bytes).expect("extract to");

    let (old_exports, _) = discover_exports(&old_root).expect("discover old");
    let (new_exports, _) = discover_exports(&new_root).expect("discover new");

    // LSP-degraded forced (mirrors test harness for parity).
    let mut findings: Vec<Finding> =
        compare::compare_exports(&old_exports, &new_exports, &new_root, false);
    findings.extend(compare::metadata::compare_metadata(&old_root, &new_root));
    findings.extend(compare::compare_exports_map_diff(&old_root, &new_root));
    findings.extend(compare::compare_structural_diff(
        &old_root,
        &new_root,
        &old_exports,
        &new_exports,
    ));
    findings.extend(compare::compare_asset_diff(&old_root, &new_root));

    let mut seen = HashSet::new();
    findings.retain(|f| seen.insert((f.rule, f.file.clone(), f.line, f.col, f.message.clone())));
    findings.sort_by(|a, b| a.severity.cmp(&b.severity));

    let exit_code: i32 = if compare::has_breaking_changes(&findings) {
        1
    } else {
        0
    };
    let mut rule_ids: Vec<String> = findings.iter().map(|f| f.rule.to_string()).collect();
    rule_ids.sort();
    rule_ids.dedup();

    // Read tarball "name@version" via the package.json inside the extracted from/to.
    let to_pkg_json: serde_json::Value = serde_json::from_slice(
        &std::fs::read(new_root.join("package.json")).expect("read to/package.json"),
    )
    .unwrap_or(serde_json::json!({}));
    let from_pkg_json: serde_json::Value = serde_json::from_slice(
        &std::fs::read(old_root.join("package.json")).expect("read from/package.json"),
    )
    .unwrap_or(serde_json::json!({}));
    let from_version = from_pkg_json
        .get("version")
        .and_then(|v| v.as_str())
        .unwrap_or("?")
        .to_string();
    let to_version = to_pkg_json
        .get("version")
        .and_then(|v| v.as_str())
        .unwrap_or("?")
        .to_string();

    let json = serde_json::json!({
        "package": pkg,
        "from_version": from_version,
        "to_version": to_version,
        "exit_code": exit_code,
        "rule_ids": rule_ids,
        "_curation_notes": format!(
            "Generated by scripts/regen-reference-suite.sh. Reference suite forces LSP-degraded mode for CI determinism. Manually review against {} release notes before committing.",
            pkg
        )
    });

    println!("{}", serde_json::to_string_pretty(&json).unwrap());
}
